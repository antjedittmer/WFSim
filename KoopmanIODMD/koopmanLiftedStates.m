function varargout = koopmanLiftedStates(task, varargin)
%KOOPMANLIFTEDSTATES Lifted states of the Koopman models (identification and MPC)
%   varargout = koopmanLiftedStates(task, ...) evaluates the lifting
%   functions of the Koopman models. The same functions are used for the
%   identification (koopmanEstimation) and in the Koopman MPC
%   (WFSimCode/bin/Kmpc), so that both use the same lifted states.
%
%   Tasks (original function names in brackets):
%   - 'urStates' (K_psi): lifted rotor effective wind speeds Ur1, Ur2
%     (polynomials, derivatives, moving means) and the inputs, one sample:
%     [psi, stateName, structPrev] = koopmanLiftedStates('urStates', x, poly, n, structPrev, yawmode)
%   - 'windStates' (koopmanstateextensionWFSim): lifted wind speeds of the
%     flow field at the turbines
%   - 'urStatesMPC', 'windStatesMPC': the versions of K_psi and
%     koopmanstateextensionWFSim used in the MPC (Kmpc/kUpdate of the
%     Koopman repo; without yawmode, recursion of dUr2 from dUr1), kept so
%     that the closed-loop results do not change
%   - 'powerFeatures' (powerFeatures): input features of the Koopman power
%     model (nonlinear power features, filtered inputs, moving means):
%     W = koopmanLiftedStates('powerFeatures', inp, featureSet, tau)
%   - 'featStatesLin' (featStatesLin): feature vector as states and inputs
%     of the linear power model
%   - 'featState' (koopFeatState): feature states of the power model in the MPC
%   - 'featLinState' (koopFeatLinState): states of the linear power model in the MPC
%   - 'filterCoeff' (inputFilterCoeff): coefficient of the input filter of
%     the turbine model
switch task
    case 'urStates',      [varargout{1:nargout}] = K_psi(varargin{:});
    case 'urStatesMPC',   [varargout{1:nargout}] = K_psiMPC(varargin{:});
    case 'windStates',    [varargout{1:nargout}] = koopmanstateextensionWFSim(varargin{:});
    case 'windStatesMPC', [varargout{1:nargout}] = koopmanstateextensionWFSimMPC(varargin{:});
    case 'powerFeatures', [varargout{1:nargout}] = powerFeatures(varargin{:});
    case 'featStatesLin', [varargout{1:nargout}] = featStatesLin(varargin{:});
    case 'featState',     [varargout{1:nargout}] = koopFeatState(varargin{:});
    case 'featLinState',  [varargout{1:nargout}] = koopFeatLinState(varargin{:});
    case 'filterCoeff',   [varargout{1:nargout}] = inputFilterCoeff(varargin{:});
    otherwise, error('koopmanLiftedStates:task', 'Unknown task %s', task);
end
end

